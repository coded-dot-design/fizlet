// API snapshots: the public types of every COMPLETE brick, committed under api/, so an export that
// changes is a reviewed change. A snapshot is the brick's built declarations (dist/*.d.ts) with the
// comments stripped (docs can change freely), following its own `export … from "./…"` re-exports
// (the kernel's index re-exports engine, pool, ring…) and the files it imports types from that no
// other COMPLETE snapshot covers (arcade names fizlet/board-page's BETA types). Types it imports from
// another COMPLETE brick are that brick's snapshot.
//
//   npm run api:write                  rebuild, then write api/<brick>.api.txt for each COMPLETE brick
//   npm run api:check                  rebuild, then fail when a snapshot is stale (run api:write)
//   npm run api:check -- --base <ref>  also fail when a snapshot changed since <ref> and the CHANGELOG's
//                                      "## Unreleased" does not name that brick (CI: --base HEAD^)
//
// COMPLETE bricks keep their API (README "Status flags"): a change here needs a CHANGELOG line, and
// a breaking one moves the brick back to BETA. Adding a newly COMPLETE brick needs no line.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

export const DIR = "api";
const EXT = ".api.txt";

/** Remove `//` and `/* *\/` comments, leaving string and template literals as they are. */
export function stripComments(text) {
  let out = "";
  for (let i = 0; i < text.length; ) {
    const c = text[i], n = text[i + 1];
    if (c === "/" && n === "/") {
      while (i < text.length && text[i] !== "\n") i++;
    } else if (c === "/" && n === "*") {
      const end = text.indexOf("*/", i + 2);
      i = end < 0 ? text.length : end + 2;
    } else if (c === '"' || c === "'" || c === "`") {
      let j = i + 1;
      while (j < text.length && text[j] !== c) j += text[j] === "\\" ? 2 : 1;
      out += text.slice(i, j + 1);
      i = j + 1;
    } else {
      out += c;
      i++;
    }
  }
  return out;
}

/** Comments out, trailing spaces trimmed, blank lines dropped: only what a consumer compiles against. */
export const normalize = (text) =>
  stripComments(text).split("\n").map((l) => l.trimEnd()).filter(Boolean).join("\n");

const REEXPORT = /^export (?:type )?(?:\*(?: as \w+)?|\{[^}]*\}) from ["'](\.{1,2}\/[^"']+)["'];?/gm;
const IMPORT = /(?:^import [^;]*? from |import\()["'](\.{1,2}\/[^"']+)["']/gm;

function resolveDts(from, spec) {
  const base = join(dirname(from), spec.replace(/\.js$/, ""));
  const file = [base + ".d.ts", join(base, "index.d.ts")].find(existsSync);
  if (!file) throw new Error(`${from}: cannot resolve ${spec}`);
  return file;
}

/**
 * The declaration files a .d.ts entry exposes: itself and, recursively, its relative re-exports.
 * With `owned` (files another snapshot covers), also the files its declarations import types from
 * that no other snapshot covers (arcade's options name fizlet/board-page's BETA types: a change
 * there changes arcade's API).
 */
export function surfaceFiles(dts, owned = null, seen = new Set()) {
  if (seen.has(dts)) return [];
  seen.add(dts);
  const text = readFileSync(dts, "utf8");
  const out = [dts];
  for (const [, spec] of text.matchAll(REEXPORT)) out.push(...surfaceFiles(resolveDts(dts, spec), owned, seen));
  if (owned)
    for (const [, spec] of text.matchAll(IMPORT)) {
      const file = resolveDts(dts, spec);
      if (!owned.has(file)) out.push(...surfaceFiles(file, owned, seen));
    }
  return out;
}

/**
 * The snapshot text of each brick ([{ id, modules: [{ name, dts }] }]) → Map id → text. A file is in
 * the snapshot of the brick that re-exports it, and in every other brick whose types reach it.
 */
export function snapshots(bricks, root = ".") {
  const own = new Map(bricks.map((b) => [b.id, new Set(b.modules.flatMap((m) => surfaceFiles(join(root, m.dts))))]));
  const out = new Map();
  for (const b of bricks) {
    const owned = new Set([...own].filter(([id]) => id !== b.id).flatMap(([, files]) => [...files]).filter((f) => !own.get(b.id).has(f)));
    const lines = [`# ${b.id}: public API of ${b.modules.map((m) => m.name).join(", ")} (COMPLETE).`, "# Generated by `npm run api:write` from the built declarations, comments stripped. Do not edit."];
    const seen = new Set();
    for (const m of b.modules) {
      lines.push("", `## ${m.name}`);
      for (const f of surfaceFiles(join(root, m.dts), owned, seen)) lines.push("", `### ${relative(root, f).split("\\").join("/")}`, normalize(readFileSync(f, "utf8")));
    }
    out.set(b.id, lines.join("\n") + "\n");
  }
  return out;
}

/** The CHANGELOG's "## Unreleased" section (without its heading), or "" when there is none. */
export function unreleased(changelog) {
  const m = changelog.match(/^## Unreleased[^\n]*\n([\s\S]*?)(?=^## |(?![\s\S]))/m);
  return m ? m[1] : "";
}

/** Words that also name a brick in the CHANGELOG, besides its module names (case-insensitive). */
const ALIASES = { kernel: ["kernel", "fizlet/kernel", "`fizlet`"], ui: ["board ui"] };
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** Does `text` name the brick: one of its module names (not as a prefix of a longer path), or an alias. */
export function mentions(brick, text) {
  const names = brick.modules.map((m) => m.name).filter((n) => n !== "fizlet");
  names.push(`fizlet/${brick.id}`);
  const exact = names.some((n) => new RegExp(`(?<![\\w/-])${esc(n)}(?![\\w/-])`).test(text));
  return exact || (ALIASES[brick.id] ?? []).some((a) => new RegExp(`(?<![\\w/-])${esc(a)}(?![\\w/-])`, "i").test(text));
}

/**
 * Compare snapshots (Maps id → text). `current` is built now, `committed` is in api/, `base` is api/
 * at the base ref (or null: then `committed` is the base). → { stale, changed, unannounced }:
 * stale ids differ between current and committed (or exist on one side only); changed ids differ
 * from the base or left it (new ids are not changes); unannounced are changed ids the CHANGELOG's
 * Unreleased section does not name.
 */
export function compare({ current, committed, base = null, changelog, bricks }) {
  const ids = new Set([...current.keys(), ...committed.keys()]);
  const stale = [...ids].filter((id) => current.get(id) !== committed.get(id)).sort();
  const from = base ?? committed, to = base ? committed : current;
  const changed = [...from.keys()].filter((id) => from.get(id) !== to.get(id)).sort();
  const notes = unreleased(changelog);
  const unannounced = changed.filter((id) => !mentions(bricks.find((b) => b.id === id) ?? { id, modules: [] }, notes));
  return { stale, changed, unannounced };
}

/** The committed snapshots: api/<id>.api.txt → Map id → text. */
export function readDir(dir) {
  const out = new Map();
  if (!existsSync(dir)) return out;
  for (const f of readdirSync(dir)) if (f.endsWith(EXT)) out.set(f.slice(0, -EXT.length), readFileSync(join(dir, f), "utf8"));
  return out;
}

/** The snapshots at a git ref (Map id → text); null when the ref has no api/ directory yet. */
export function readRef(ref, dir = DIR, cwd = ".") {
  const git = (...args) => execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  git("rev-parse", "--verify", `${ref}^{commit}`); // throws on a bad ref: CI must not pass by accident
  if (!git("ls-tree", "--name-only", ref, "--", dir).trim()) return null;
  const out = new Map();
  for (const f of git("ls-tree", "--name-only", `${ref}:${dir}`).split("\n"))
    if (f.endsWith(EXT)) out.set(f.slice(0, -EXT.length), git("show", `${ref}:${dir}/${f}`));
  return out;
}

async function main(argv) {
  const [cmd, ...rest] = argv;
  const baseAt = rest.indexOf("--base");
  const baseRef = baseAt >= 0 ? rest[baseAt + 1] : null;
  if (!["write", "check"].includes(cmd) || (baseAt >= 0 && !baseRef)) {
    console.error("usage: node scripts/api-snapshot.mjs write | check [--base <git ref>]");
    return 2;
  }
  if (!rest.includes("--no-build")) execFileSync("node", ["scripts/build.mjs"], { stdio: ["ignore", "ignore", "inherit"] });
  const { BRICKS } = await import("../site/bricks.mjs");
  const complete = BRICKS.filter((b) => b.status === "complete");
  const current = snapshots(complete);
  const committed = readDir(DIR);
  const changelog = readFileSync("CHANGELOG.md", "utf8");

  if (cmd === "write") {
    const { changed, unannounced } = compare({ current, committed, changelog, bricks: BRICKS });
    rmSync(DIR, { recursive: true, force: true });
    mkdirSync(DIR, { recursive: true });
    for (const [id, text] of current) writeFileSync(join(DIR, id + EXT), text);
    console.log(`API snapshots: ${current.size} COMPLETE bricks written to ${DIR}/${changed.length ? `; changed: ${changed.join(", ")}` : ", no change"}.`);
    for (const id of unannounced) console.warn(`  ${id}: add a line naming it under "## Unreleased" in CHANGELOG.md (api:check fails without one).`);
    return 0;
  }

  const base = baseRef ? readRef(baseRef) : null;
  const { stale, changed, unannounced } = compare({ current, committed, base, changelog, bricks: BRICKS });
  const errors = [];
  if (stale.length) errors.push(`stale API snapshots (an export changed, or a brick became or stopped being COMPLETE): ${stale.join(", ")}. Run npm run api:write and commit ${DIR}/.`);
  for (const id of unannounced)
    errors.push(`${id}: its public API changed${baseRef ? ` since ${baseRef}` : ""} but CHANGELOG.md's "## Unreleased" does not name it (e.g. \`fizlet/${id}\`). COMPLETE bricks keep their API: say what changed, and move it back to BETA if it breaks.`);
  if (errors.length) {
    for (const e of errors) console.error(`::error::${e}`);
    return 1;
  }
  const note = baseRef && !base ? ` (${baseRef} has no ${DIR}/ yet: nothing to compare)` : changed.length ? `; changed and in the CHANGELOG: ${changed.join(", ")}` : "";
  console.log(`API snapshots: ${current.size} COMPLETE bricks match ${DIR}/${note}.`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exitCode = await main(process.argv.slice(2));
